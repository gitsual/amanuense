# ── Reading the repos ─────────────────────────────────────────────────────────

def _git(repo: Path, *args: str, run=subprocess.run) -> str:
    proc = run(["git", "-C", str(repo), *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    return proc.stdout if proc.returncode == 0 else ""


def _json_at(repo: Path, ref: str, path: str, run) -> dict:
    try:
        data = json.loads(_git(repo, "show", f"{ref}:{path}", run=run) or "null")
    except json.JSONDecodeError:
        return {}
    return data if isinstance(data, dict) else {}


def branches(repo: Path, run=subprocess.run) -> list[dict]:
    """Every branch, newest commit first: name, sha and date."""
    out = _git(repo, "for-each-ref", "--sort=-committerdate",
               "--format=%(refname)%09%(objectname)%09%(committerdate:iso-strict)%09%(symref)",
               "refs/heads", "refs/remotes", run=run)
    seen, found = set(), []
    for line in out.splitlines():
        ref, sha, when, alias = (line.split("\t") + ["", "", "", ""])[:4]
        name = re.sub(r"^refs/(heads|remotes/origin|remotes)/", "", ref)
        if alias or name in seen or name == "HEAD":
            continue
        seen.add(name)
        found.append({"branch": name, "ref": ref, "sha": sha, "when": when})
    return found


def packages_at(repo: Path, ref: str, scope: str, run=subprocess.run) -> dict[str, dict]:
    """Packages of the scope on one branch, from brick.metadata.json or from its package.json files."""
    meta = _json_at(repo, ref, "brick.metadata.json", run)
    manifests: list[tuple[str, dict]] = []
    if meta.get("packages"):
        manifests = [(p.get("manifest", "package.json"), p) for p in meta["packages"] if isinstance(p, dict)]
    else:
        files = _git(repo, "ls-tree", "-r", "--name-only", ref, run=run).splitlines()
        manifests = [(f, {}) for f in files
                     if f.endswith("package.json") and "node_modules/" not in f and "/dist/" not in f
                     and not f.startswith("dist/") and "__fixtures__" not in f and f.count("/") <= 4]
    found = {}
    for path, declared in manifests:
        pkg = _json_at(repo, ref, path, run)
        name = pkg.get("name") or declared.get("name", "")
        if not name or not pkg.get("version") or (scope and not name.startswith(scope + "/")) \
                or (pkg.get("private") and not declared):
            continue
        peers = {**pkg.get("peerDependencies", {}), **pkg.get("dependencies", {})}
        found[name] = {
            "version": pkg.get("version", ""), "description": pkg.get("description", ""), "manifest": path,
            "contracts": sorted(f"{k} {v}" for k, v in peers.items() if "contract" in k),
            "category": (meta.get("classification") or {}).get("category", ""),
            "audience": (meta.get("classification") or {}).get("audience", ""),
            "technology": meta.get("technology", ""), "kind": meta.get("kind", ""),
        }
    return found


# ── Registry and pages ────────────────────────────────────────────────────────

def registry_versions(registry: str, name: str, fetch: Callable[[str], bytes] | None = None) -> dict:
    """Published versions of a package; status unchecked, unreachable, unpublished or published."""
    if not registry:
        return {"status": "unchecked", "versions": []}
    url = registry.rstrip("/") + "/" + urllib.parse.quote(name, safe="@")
    fetch = fetch or (lambda u: urllib.request.urlopen(u, timeout=4).read())
    try:
        doc = json.loads(fetch(url))
    except urllib.error.HTTPError as exc:
        return {"status": "unpublished" if exc.code == 404 else "unreachable", "versions": []}
    except Exception:
        return {"status": "unreachable", "versions": []}
    versions = sorted(doc.get("versions", {}), key=_version_key)
    return {"status": "published" if versions else "unpublished", "versions": versions}


def _version_key(v: str) -> tuple:
    core, _, pre = v.partition("-")
    nums = [int(x) if x.isdigit() else 0 for x in core.split(".")[:3]]
    return (*nums, pre == "", pre)


def coherence(branch_version: str, published: list[str]) -> str:
    if not branch_version or not published:
        return "unknown"
    base = branch_version.partition("-")[0]
    top = max((v.partition("-")[0] for v in published), key=_version_key)
    if base == top:
        return "same"
    return "ahead" if _version_key(base) > _version_key(top) else "behind"


def citing_pages(names: list[str], pages: list[Page]) -> list[str]:
    patterns = [re.compile(rf"(?<![\w-]){re.escape(n.lower())}(?![\w-])") for n in names if n]
    return list(dict.fromkeys(p.title for p in pages if any(r.search(p.markdown.lower()) for r in patterns)))


# ── The catalogue ─────────────────────────────────────────────────────────────

def _display(name: str) -> str:
    short = re.sub(r"^(cci-)?(capability-|hmi-)?", "", name.split("/")[-1])
    return short.replace("-", " ").strip().capitalize() or name


def build_catalog(repos: list[Path], pages: list[Page], config: dict, run=subprocess.run,
                  fetch: Callable[[str], bytes] | None = None) -> dict:
    cfg = {**DEFAULTS, **config}
    entries: dict[str, dict] = {}
    for repo in repos:
        for b in branches(repo, run):
            for name, pkg in packages_at(repo, b["ref"], cfg["scope"], run).items():
                e = entries.setdefault(name, {"package": name, "repo": repo.name.removesuffix(".git"),
                                              "branches": [], **{k: pkg[k] for k in (
                                                  "description", "category", "audience", "technology", "kind")}})
                if e["repo"] != repo.name.removesuffix(".git"):
                    continue  # the same package in another repo is a copy, not its home
                e["branches"].append({"branch": b["branch"], "version": pkg["version"], "sha": b["sha"][:10],
                                      "when": b["when"], "contracts": pkg["contracts"]})
                for k in ("category", "audience", "technology", "kind", "description"):
                    e[k] = e[k] or pkg[k]
    # Packages the team needs that live outside these repos: listed so the gap shows.
    for name, extra in cfg["overrides"].items():
        if extra.get("external") and name not in entries:
            entries[name] = {"package": name, "repo": "", "branches": [], "description": "", "category": "",
                             "audience": "", "technology": "", "kind": "",
                             "newest": {"branch": "", "version": extra["external"], "sha": "", "when": "",
                                        "contracts": []}}
    catalog = []
    for name, e in sorted(entries.items()):
        e.update(cfg["overrides"].get(name, {}))
        newest = e["branches"][0] if e["branches"] else e["newest"]
        develop = next((b["version"] for b in e["branches"] if b["branch"] in ("develop", "origin/develop")), "")
        reg = registry_versions(cfg["registry"], name, fetch)
        e.update({
            "name": e.get("name") or _display(name),
            "category": e["category"] or "uncategorised",
            "category_label": cfg["categories"].get(e["category"], e["category"] or L("uncategorised")),
            "delivery": e.get("delivery", cfg["delivery"]),
            "newest": newest, "develop": develop, "contracts": newest["contracts"],
            "registry": reg, "coherence": coherence(newest["version"], reg["versions"]),
            "pages": citing_pages([name, e["repo"]], pages),
        })
        catalog.append(e)
    return {"generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "scope": cfg["scope"],
            "registry": cfg["registry"], "repos": len(repos), "packages": catalog}


