STATUS_COLOR = {"published": "#1f7a3a", "same": "#1f7a3a", "unpublished": "#9a5b00", "ahead": "#9a5b00",
                "behind": "#a12a2a", "unreachable": "#a12a2a", "unchecked": "#5b6470", "unknown": "#5b6470"}


def render_confluence(catalog: dict) -> str:
    """Plain tables with inline styles: Confluence keeps them on paste and runs no script."""
    e = html.escape
    out = [f"<h1>{e(L('title'))}</h1>", f"<p>{e(L('lead'))}</p>",
           f"<p><em>{e(L('confluence_note', when=catalog['generated'], repos=catalog['repos']))}</em></p>"]
    groups: dict[str, list] = {}
    for p in catalog["packages"]:
        groups.setdefault(p["category_label"], []).append(p)
    head = [L("package"), L("branch"), L("develop"), L("registry"), L("coherence"), L("contracts"), L("repo"),
            L("pages")]
    for label, items in sorted(groups.items()):
        out.append(f"<h2>{e(label)} ({len(items)})</h2>")
        out.append('<table><thead><tr>' + "".join(f"<th>{e(h)}</th>" for h in head) + "</tr></thead><tbody>")
        for p in items:
            reg = p["registry"]
            reg_text = L(reg["status"]) + (f" · {reg['versions'][-1]}" if reg["versions"] else "")
            cells = [
                f"<strong>{e(p['name'])}</strong><br/><code>{e(p['package'])}</code>",
                f"{e(p['newest']['version'])}<br/><small>{e(p['newest']['branch'])} · {e(p['newest']['sha'])}</small>",
                e(p["develop"] or "—"),
                _lozenge(reg["status"], reg_text), _lozenge(p["coherence"], L(p["coherence"])),
                "<br/>".join(f"<code>{e(c)}</code>" for c in p["contracts"]) or e(L("none")),
                f"<code>{e(p['repo'])}</code>" if p["repo"] else _lozenge("behind", L("external")),
                "<br/>".join(e(t) for t in p["pages"][:4]) or e(L("uncited")),
            ]
            out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
        out.append("</tbody></table>")
    body = "\n".join(out)
    return (f'<!doctype html><html lang="{i18n.current()}"><head><meta charset="utf-8"><title>{e(L("title"))}'
            f"</title></head><body>\n{body}\n</body></html>\n")


def _lozenge(status: str, text: str) -> str:
    color = STATUS_COLOR.get(status, "#5b6470")
    return (f'<span style="color:{color};border:1px solid {color};border-radius:3px;padding:0 4px;'
            f'font-size:12px;white-space:nowrap">{html.escape(text)}</span>')


def render_index(catalog: dict) -> str:
    labels = {k: L(k) for k in LABELS if k not in ("shown", "confluence_note")}
    labels["shown"] = LABELS["shown"].get(i18n.current(), LABELS["shown"]["en"])
    data = json.dumps({"catalog": catalog, "labels": labels, "colors": STATUS_COLOR}, ensure_ascii=False)
    data = data.replace("</", "<\\/")
    return (INDEX_HTML.replace("__LANG__", i18n.current()).replace("__TITLE__", html.escape(L("title")))
            .replace("__DATA__", data))


