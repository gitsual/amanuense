def write_radiator(root: Path, catalog: dict) -> Path:
    out = root / i18n.name("out") / "radiador"
    out.mkdir(parents=True, exist_ok=True)
    (out / "catalogo.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=1), encoding="utf-8")
    (out / "PARA-CONFLUENCE.html").write_text(render_confluence(catalog), encoding="utf-8")
    (out / "index.html").write_text(render_index(catalog), encoding="utf-8")
    return out / "index.html"


def load_config(root: Path) -> dict:
    path = root / CONFIG
    return json.loads(path.read_text(encoding="utf-8-sig")) if path.is_file() else {}  # Notepad adds a BOM
